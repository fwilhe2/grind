//! `grind init` — a directory set up for writing `.rhai` and `.grind` in an editor
//! (`doc/init.md`, I1 and I2).
//!
//! **What it writes is `doc/editor-setup.md` §3 and §6, executed**, plus the repository files
//! `doc/init.md` §3.7–§3.8 argue for, a starter, and a README saying what to do first and what
//! the editor will and will not do. The scope line is §3.4's: a file is written only if a person
//! following this repository's own documentation would otherwise have written it by hand — or,
//! for the README, would otherwise have had to discover its contents by being surprised.
//!
//! Three rules, each a test in `cli/tests/init.rs`:
//!
//! * **Never clobber.** A file that exists with other content is *kept*, byte for byte, and the
//!   report says what it would have needed (`doc/init.md` §3.6); `--force` replaces it. A file
//!   that already holds exactly what would be written is *unchanged*, so a second run writes
//!   nothing at all.
//! * **Nothing outside the directory.** No editor is touched — extensions are recommended in
//!   `extensions.json`, never installed (§3.2) — and git is configured only when the directory
//!   is itself a repository's root, in that repository's own `.git/config`.
//! * **No project file.** Nothing written here is read back by `grind` (§3.1): delete any of it
//!   and every command behaves as before.
//!
//! The files are of two kinds (§3.5), and I2 is where they part. **Generated** ones are this
//! binary's answer to "what can a script say", owned by grind: each carries a header naming the
//! build that wrote it, a plain `init` reports one whose vocabulary differs from this binary's as
//! `stale`, and `--update` rewrites exactly those and touches nothing else. **Seeded** ones are a
//! starting point that belongs to the user from the moment it exists, and only `--force` ever
//! writes over one.
//!
//! **Stale is decided by content, not by the header.** The header's commit is the one
//! `grind-core` was last built at (`core/build.rs`), which an incremental build does not refresh,
//! and a new commit that registered no function has not made anybody's completion wrong. So the
//! body under the header is compared with what this binary would write, and the header itself is
//! information for a person.

use std::path::Path;
use std::process::Command;

use serde::Serialize;

const EXTENSIONS: &str = include_str!("../templates/vscode/extensions.json");
const SETTINGS: &str = include_str!("../templates/vscode/settings.json");
const TASKS: &str = include_str!("../templates/vscode/tasks.json");

const EDITORCONFIG: &str = include_str!("../templates/repo/editorconfig");
const GITATTRIBUTES: &str = include_str!("../templates/repo/gitattributes");

/// What to do first and what to expect — the things measured about the editor that a person
/// would otherwise find out by being surprised (`doc/editor-setup.md` §8). The top is the
/// starter's own (`Template::readme`), this is the rest. Named in lower case in the tree so it is
/// not mistaken for this repository's own.
const README_COMMON: &str = include_str!("../templates/repo/readme-common.md");

/// What git runs to turn an OpenDocument package into text for a diff (`doc/init.md` §3.8).
const TEXTCONV: &str = "grind project";

/// How a generated file begins, so one this binary wrote can be told from one a person did.
const GENERATED: &str = "// Generated by grind ";

/// Which starter `init` writes (`doc/init.md` §4.4). Each must lint clean, spelling included —
/// a starter that greets a newcomer with warnings teaches them to ignore the linter — which
/// `cli/tests/init.rs` checks by running every one.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, clap::ValueEnum)]
pub enum Template {
    /// A script that builds a spreadsheet out of the data beside it, with its tests
    #[default]
    Generator,
    /// A spreadsheet written by hand, as a projection
    Sheet,
    /// A text document written by hand, as a projection
    Text,
    /// The editor and repository files, and no starter
    None,
}

impl Template {
    /// The starter's files, path and content.
    fn files(self) -> &'static [(&'static str, &'static str)] {
        match self {
            Template::Generator => &[
                (
                    "model.rhai",
                    include_str!("../templates/generator/model.rhai"),
                ),
                (
                    "data.json",
                    include_str!("../templates/generator/data.json"),
                ),
            ],
            Template::Sheet => &[("book.grind", include_str!("../templates/sheet/book.grind"))],
            Template::Text => &[("notes.grind", include_str!("../templates/text/notes.grind"))],
            Template::None => &[],
        }
    }

    /// The top of the README: what the starter is, and the commands that work on it.
    fn readme(self) -> &'static str {
        match self {
            Template::Generator => include_str!("../templates/generator/readme.md"),
            Template::Sheet => include_str!("../templates/sheet/readme.md"),
            Template::Text => include_str!("../templates/text/readme.md"),
            Template::None => include_str!("../templates/none/readme.md"),
        }
    }

    /// Something built from the starter, which is derived and stays out of history. Only a
    /// script builds anything; a hand-written projection is the source itself.
    fn gitignore(self) -> Option<&'static str> {
        match self {
            Template::Generator => Some(include_str!("../templates/repo/gitignore")),
            _ => None,
        }
    }

    /// The first thing to run on the starter.
    fn first(self, dir: &Path) -> Option<(String, String)> {
        let at = |file: &str| shown(&dir.join(file));
        match self {
            Template::Generator => Some((
                format!("grind test {}", at("model.rhai")),
                "run the starter's tests — or Ctrl+Shift+B in VS Code to build it".to_owned(),
            )),
            Template::Sheet => Some((
                format!("grind sheet recalc {}", at("book.grind")),
                "write every formula's answer into the starter — one line of diff per cell"
                    .to_owned(),
            )),
            Template::Text => Some((
                format!("grind text view {}", at("notes.grind")),
                "read the starter as text".to_owned(),
            )),
            Template::None => None,
        }
    }
}

/// What `grind init` was asked to do.
#[derive(Clone, Copy, Debug, Default)]
pub struct Options {
    /// The starter, when one was named. Unnamed, a directory `init` has not set up before gets
    /// the default and one it has gets none: running it again must not add a second starter
    /// beside the first.
    pub template: Option<Template>,
    /// Replace files that exist with other content, generated or seeded.
    pub force: bool,
    /// Rewrite the generated files only (`doc/init.md` §3.5); write and touch nothing else.
    pub update: bool,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    /// The binary's own answer; rewritten by `--update`.
    Generated,
    /// A starting point, the user's once written.
    Seeded,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Action {
    /// It did not exist, and now does.
    Wrote,
    /// It already held this — or, generated, the same vocabulary under an older header.
    Unchanged,
    /// It exists with other content, and was left alone.
    Kept,
    /// A generated file whose vocabulary is not this binary's; `--update` rewrites it.
    Stale,
    /// A stale generated file, rewritten by `--update`.
    Updated,
    /// It existed with other content, and `--force` replaced it.
    Replaced,
    /// A setting was made — git's, which is not a file of ours.
    Set,
    /// Not done, for the reason in the note.
    Skipped,
}

impl Action {
    pub fn label(self) -> &'static str {
        match self {
            Action::Wrote => "wrote",
            Action::Unchanged => "unchanged",
            Action::Kept => "kept",
            Action::Stale => "stale",
            Action::Updated => "updated",
            Action::Replaced => "replaced",
            Action::Set => "set",
            Action::Skipped => "skipped",
        }
    }
}

/// One file, or one setting, and what happened to it.
#[derive(Debug, Serialize)]
pub struct Entry {
    /// Relative to the directory, with `/` whatever the platform.
    pub path: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub kind: Option<Kind>,
    pub action: Action,
    /// Why, or what a kept file still needs.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub note: Option<String>,
}

/// What `grind init` did, and what is left for the person to do.
#[derive(Debug, Serialize)]
pub struct InitReport {
    pub dir: String,
    pub entries: Vec<Entry>,
    /// Commands to run next, each with what it is for.
    pub next: Vec<(String, String)>,
}

/// One file `init` would write: where, of which kind, what, and — for a seeded file the user
/// already has — what it says a kept copy is missing, if it can tell.
struct Plan {
    path: &'static str,
    kind: Kind,
    content: String,
    missing: Option<fn(&str) -> Option<&'static str>>,
}

/// The generated files: this binary's vocabulary, each under a header.
fn generated(projection_snippets: &str) -> Vec<Plan> {
    // The commit as well as the version, because the suite's version number does not move yet.
    // Information for a person; staleness is decided by the body (see the module comment).
    let version = format!(
        "{} (commit {})",
        env!("CARGO_PKG_VERSION"),
        grind_core::build_info::COMMIT
    );
    let file = |path, what: &str, command: &str, body: String| Plan {
        path,
        kind: Kind::Generated,
        content: format!(
            "{GENERATED}{version}: {what}.\n\
             // Do not edit it. After upgrading grind, `grind init --update` writes it again, as\n\
             // does `{command}`.\n{}",
            ensure_newline(body)
        ),
        missing: None,
    };
    vec![
        file(
            ".vscode/grind.code-snippets",
            "every function a script can call, as VS Code snippets",
            "grind definitions --snippets > .vscode/grind.code-snippets",
            grind_build::snippets(),
        ),
        file(
            ".vscode/grind-projection.code-snippets",
            "every node of a .grind, as VS Code snippets",
            "grind definitions --projection > .vscode/grind-projection.code-snippets",
            projection_snippets.to_owned(),
        ),
        file(
            "grind.d.rhai",
            "every function a script can call, as a Rhai definition file",
            "grind definitions > grind.d.rhai",
            grind_build::definitions(),
        ),
    ]
}

/// The seeded files, in the order the report lists them. The README is the starter's, so it is
/// left out when no starter was asked for in a directory set up before — its README describes
/// the starter it got the first time, and comparing that with another would only ever say
/// `kept`.
fn seeded(template: Template, readme: bool) -> Vec<Plan> {
    let file = |path, content: &str, missing| Plan {
        path,
        kind: Kind::Seeded,
        content: content.to_owned(),
        missing,
    };
    let mut files: Vec<Plan> = template
        .files()
        .iter()
        .map(|(path, content)| file(path, content, None))
        .collect();
    if readme {
        files.push(file(
            "README.md",
            &format!("{}{README_COMMON}", template.readme()),
            None,
        ));
    }
    files.push(file(".vscode/extensions.json", EXTENSIONS, None));
    files.push(file(
        ".vscode/settings.json",
        SETTINGS,
        Some(|text| {
            (!text.contains("*.grind")).then_some(
                "add \"files.associations\": { \"*.grind\": \"kdl\" } — without it a .grind is plain text",
            )
        }),
    ));
    files.push(file(".vscode/tasks.json", TASKS, None));
    files.push(file(".editorconfig", EDITORCONFIG, None));
    if let Some(ignore) = template.gitignore() {
        files.push(file(".gitignore", ignore, None));
    }
    files.push(file(
        ".gitattributes",
        GITATTRIBUTES,
        Some(|text| {
            (!text.contains("diff=grind"))
                .then_some("add `*.ods diff=grind` and `*.odt diff=grind` for diffs that read")
        }),
    ));
    files
}

fn ensure_newline(mut text: String) -> String {
    if !text.ends_with('\n') {
        text.push('\n');
    }
    text
}

/// A generated file without its header: what decides whether it is stale.
fn body(text: &str) -> &str {
    let mut rest = text;
    while rest.starts_with("//") {
        rest = rest.split_once('\n').map_or("", |(_, after)| after);
    }
    rest
}

/// Set up `dir` — created if missing — and report what was done to each file.
pub fn init(dir: &Path, options: Options, projection_snippets: &str) -> Result<InitReport, String> {
    if dir.exists() && !dir.is_dir() {
        return Err(format!("{} is a file, not a directory", dir.display()));
    }
    std::fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;

    // Set up before when one of grind's generated files is there under its header.
    let set_up = generated(projection_snippets).iter().any(|file| {
        std::fs::read_to_string(dir.join(file.path)).is_ok_and(|text| text.starts_with(GENERATED))
    });
    let template = match options.template {
        Some(template) => template,
        None if set_up => Template::None,
        None => Template::default(),
    };

    let mut entries = Vec::new();
    if !options.update {
        for file in seeded(template, !(set_up && options.template.is_none())) {
            entries.push(place(dir, file, options)?);
        }
    }
    for file in generated(projection_snippets) {
        entries.push(place(dir, file, options)?);
    }
    let repository = dir.join(".git").is_dir();
    if repository && !options.update {
        entries.push(textconv(dir));
    }

    let mut next = Vec::new();
    if !options.update {
        next.push((
            format!("code {}", shown(dir)),
            "open it, install the extensions it offers, and trust the folder — in Restricted \
             Mode a .grind stays plain text and no task runs (see README.md)"
                .to_owned(),
        ));
        next.extend(template.first(dir));
        if !repository {
            next.push((
                format!("git config diff.grind.textconv \"{TEXTCONV}\""),
                "once per clone, after `git init`: diffs of .ods and .odt that read".to_owned(),
            ));
        }
    }
    if entries.iter().any(|e| e.action == Action::Stale) {
        next.push((
            format!("grind init --update {}", shown(dir)),
            "rewrite the stale vocabulary, and nothing else".to_owned(),
        ));
    }
    Ok(InitReport {
        dir: dir.display().to_string(),
        entries,
        next,
    })
}

/// Write one file unless that would overwrite something it should not.
fn place(dir: &Path, file: Plan, options: Options) -> Result<Entry, String> {
    let target = dir.join(file.path);
    let existing = match std::fs::read(&target) {
        Ok(bytes) => Some(String::from_utf8_lossy(&bytes).into_owned()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(format!("cannot read {}: {e}", target.display())),
    };
    let entry = |action, note: Option<String>| Entry {
        path: file.path.to_owned(),
        kind: Some(file.kind),
        action,
        note,
    };
    let action = match (&existing, file.kind) {
        (None, _) => Action::Wrote,
        (Some(text), _) if *text == file.content => return Ok(entry(Action::Unchanged, None)),
        // Grind's own file: the same vocabulary under an older header is not worth a diff, and a
        // different one is stale until somebody asks for it to be rewritten.
        (Some(text), Kind::Generated) if text.starts_with(GENERATED) => {
            if body(text) == body(&file.content) {
                return Ok(entry(Action::Unchanged, None));
            }
            if !(options.update || options.force) {
                return Ok(entry(
                    Action::Stale,
                    Some("written by another grind; `grind init --update` rewrites it".to_owned()),
                ));
            }
            Action::Updated
        }
        (Some(text), kind) if !options.force => {
            let note = match (kind, file.missing.and_then(|missing| missing(text))) {
                (Kind::Generated, _) => {
                    "not written by grind init, so not rewritten; --force replaces it".to_owned()
                }
                (Kind::Seeded, Some(advice)) => format!("exists and is yours; {advice}"),
                (Kind::Seeded, None) => "exists and is yours; --force replaces it".to_owned(),
            };
            return Ok(entry(Action::Kept, Some(note)));
        }
        (Some(_), _) => Action::Replaced,
    };
    if let Some(parent) = target.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
    }
    std::fs::write(&target, &file.content)
        .map_err(|e| format!("cannot write {}: {e}", target.display()))?;
    Ok(entry(action, None))
}

/// Point this repository's `diff=grind` at `grind project` — in `.git/config`, which is not
/// committed, so it is the one thing a clone does not get (`doc/init.md` §3.8). A value someone
/// already set is theirs, `--force` or not.
fn textconv(dir: &Path) -> Entry {
    let entry = |action, note: &str| Entry {
        path: ".git/config".to_owned(),
        kind: None,
        action,
        note: Some(note.to_owned()),
    };
    let git = |args: &[&str]| Command::new("git").arg("-C").arg(dir).args(args).output();
    match git(&["config", "--local", "--get", "diff.grind.textconv"]) {
        Err(_) => entry(Action::Skipped, "git is not on PATH"),
        Ok(out) if out.status.success() => {
            let current = String::from_utf8_lossy(&out.stdout).trim().to_owned();
            match current == TEXTCONV {
                true => entry(Action::Unchanged, "diff.grind.textconv"),
                false => entry(
                    Action::Kept,
                    &format!("diff.grind.textconv is already \"{current}\", and is yours"),
                ),
            }
        }
        Ok(_) => match git(&["config", "--local", "diff.grind.textconv", TEXTCONV]) {
            Ok(out) if out.status.success() => entry(
                Action::Set,
                "diff.grind.textconv = \"grind project\" — .ods and .odt diff as text",
            ),
            _ => entry(Action::Skipped, "git config failed"),
        },
    }
}

/// A path as a person would type it back: `./model.rhai` is `model.rhai`, and one with a
/// space in it is quoted.
fn shown(path: &Path) -> String {
    let path = path.strip_prefix(".").unwrap_or(path);
    let text = match path.as_os_str().is_empty() {
        true => ".".to_owned(),
        false => path.display().to_string(),
    };
    match text.contains(' ') {
        true => format!("\"{text}\""),
        false => text,
    }
}

impl InitReport {
    pub fn print_text(&self) {
        let width = self.entries.iter().map(|e| e.path.len()).max().unwrap_or(0);
        for entry in &self.entries {
            match &entry.note {
                Some(note) => {
                    println!("{:<9} {:<width$}  {note}", entry.action.label(), entry.path)
                }
                None => println!("{:<9} {}", entry.action.label(), entry.path),
            }
        }
        if !self.next.is_empty() {
            println!("\nnext:");
            for (command, why) in &self.next {
                println!("  {command}\n      {why}");
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_body_is_what_is_under_the_header() {
        assert_eq!(body("// one\n// two\n{\n}\n"), "{\n}\n");
        assert_eq!(body("module static;\n"), "module static;\n");
        assert_eq!(body("// only a header\n"), "");
    }
}
